import './domShim.js';
import assert from 'node:assert/strict';
import React from 'react';
import { renderToString } from 'react-dom/server';
import { MemoryRouter } from 'react-router-dom';
import { HeaderProvider } from '@/context/HeaderContext';
import ListLayout from '@/components/ListLayout';
import Pagination from '@/components/Pagination';
import DataTable from '@/components/List/DataTable';
import i18n from '@/i18n/index.js';
import { I18nextProvider } from 'react-i18next';
const wrap = (node) => renderToString(<I18nextProvider i18n={i18n}><MemoryRouter><HeaderProvider>{node}</HeaderProvider></MemoryRouter></I18nextProvider>);
const html = wrap(<ListLayout actionBar={<div>Toolbar marker</div>} tabs={<button aria-pressed="true">Tab marker</button>} pagination={<Pagination currentPage={1} totalPages={12} totalItems={240} pageSize={20} onPageChange={() => {}} />} contentMode="children" floatingAction={<button>Action marker</button>}><div>Body marker</div></ListLayout>);
assert(html.indexOf('Tab marker') < html.indexOf('Body marker'));
assert(html.indexOf('Body marker') < html.indexOf('Toolbar marker'));
assert(html.indexOf('Body marker') < html.indexOf('Action marker'));
assert(html.includes('type="number"'));
assert(/\/\s*(?:<!--.*?-->)?12/.test(html));
assert(!html.includes('Showing 1'));
assert(!wrap(<Pagination currentPage={1} totalPages={1} totalItems={2} pageSize={20} onPageChange={() => {}} />).includes('<nav'));
const empty = wrap(<ListLayout tabs={<button>Empty tab marker</button>} isEmpty emptyTitle="No rows" />);
assert(empty.includes('Empty tab marker'));
const table = wrap(<DataTable showIndex={false} columns={[{ id: 'select', header: 'Select', cell: () => <input type="checkbox" /> }, { id: 'id', header: 'ID' }, { id: 'name', header: 'Name' }]} data={[{ id: 'ID-1', name: 'Example' }]} />);
const cells = [...table.matchAll(/<td[^>]*>[\s\S]*?<\/td>/g)].map((match) => match[0]);
assert.equal(cells.filter((cell) => cell.includes('font-medium text-[var(--text-secondary)]')).length, 1);
assert(cells[1].includes('font-medium text-[var(--text-secondary)]') && cells[1].includes('ID-1'));
assert(cells[2].includes('text-muted-foreground'));
console.log('Compact list and pagination regression checks passed');
