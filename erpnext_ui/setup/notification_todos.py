def setup_notification_todo_fields():
	"""Install Notification task settings and the ToDo idempotency key."""
	if not frappe.db.exists("DocType", "Notification") or not frappe.db.exists("DocType", "ToDo"):
		return

	# setup_todo_fields runs first in after_migrate and adds this ToDo category field.
	if not frappe.db.has_column("ToDo", "custom_for_information_only"):
		frappe.throw("Run setup_todo_fields before adding Notification task settings.")

	create_custom_fields(
		{
			"Notification": NOTIFICATION_TODO_FIELDS,
			"ToDo": TODO_NOTIFICATION_FIELDS,
		},
		update=True,
	)
	frappe.clear_cache(doctype="Notification")
	frappe.clear_cache(doctype="ToDo")
